#!/usr/bin/env python3
"""Generate a navigable index of the debug-experiments ledgers.

The folder holds 150+ ledgers and its README explicitly forbids deleting failed
experiments, since failures prevent repeat work. So the problem is not volume,
it is that the corpus has no table of contents and status metadata has drifted:
only a minority of ledgers carry a Status line, and several use values outside
the vocabulary the README defines.

This writes debug-experiments/INDEX.md, grouped newest-first by month, and
reports which ledgers are missing metadata so they can be fixed over time.
It never edits or deletes a ledger.

Usage:
    python tools/index_debug_experiments.py
    python tools/index_debug_experiments.py --check   # report only, no write
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LEDGERS = REPO / "debug-experiments"
INDEX = LEDGERS / "INDEX.md"

SKIP = {"README.md", "_template.md", "INDEX.md"}

DATE_RE = re.compile(r"^(\d{4})(\d{2})(\d{2})-")
STATUS_RE = re.compile(r"^\s*-?\s*Status:\s*`?([^`\n]+?)`?\s*$", re.IGNORECASE | re.MULTILINE)
SCOPE_RE = re.compile(r"^\s*-?\s*Platform scope:\s*`?([^`\n]+?)`?\s*$", re.IGNORECASE | re.MULTILINE)
H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)

# Vocabulary the README defines.
KNOWN_STATUS = {
    "proposed", "measuring", "windows-pass", "android-pass", "failed", "parked",
}


def parse(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    m = DATE_RE.match(path.name)
    date = f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else ""
    month = f"{m.group(1)}-{m.group(2)}" if m else "undated"

    status_m = STATUS_RE.search(text)
    status = status_m.group(1).strip() if status_m else ""

    h1_m = H1_RE.search(text)
    title = h1_m.group(1).strip() if h1_m else path.stem

    scope_m = SCOPE_RE.search(text)
    scope = scope_m.group(1).strip() if scope_m else ""
    if "|" in scope:  # unfilled template placeholder
        scope = ""

    return {
        "path": path, "name": path.name, "date": date, "month": month,
        "status": status, "scope": scope, "title": title,
        "size": path.stat().st_size,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report only, do not write")
    args = ap.parse_args()

    if not LEDGERS.is_dir():
        raise SystemExit(f"not found: {LEDGERS}")

    entries = [parse(p) for p in sorted(LEDGERS.glob("*.md")) if p.name not in SKIP]
    if not entries:
        raise SystemExit("no ledgers found")

    by_month = defaultdict(list)
    for e in entries:
        by_month[e["month"]].append(e)

    missing_status = [e for e in entries if not e["status"]]
    odd_status = sorted({
        e["status"] for e in entries
        if e["status"] and e["status"].lower() not in KNOWN_STATUS
    })

    lines = [
        "# Debug Experiments Index",
        "",
        "Generated by `tools/index_debug_experiments.py`. Do not edit by hand.",
        "",
        f"{len(entries)} ledgers across {len(by_month)} months. See `README.md` for the",
        "rules and the status vocabulary. Failed experiments are kept deliberately.",
        "",
    ]

    for month in sorted(by_month, reverse=True):
        rows = sorted(by_month[month], key=lambda e: e["name"], reverse=True)
        lines += [f"## {month}", ""]
        lines += ["| Ledger | Status | Scope | Title |", "| --- | --- | --- | --- |"]
        for e in rows:
            title = e["title"].replace("|", "\\|")[:70]
            lines.append(
                f"| [{e['name'][:60]}]({e['name']}) | {e['status'] or '—'} "
                f"| {e['scope'] or '—'} | {title} |"
            )
        lines.append("")

    lines += ["## Metadata hygiene", ""]
    lines.append(f"- {len(missing_status)} of {len(entries)} ledgers have no `Status:` line.")
    if odd_status:
        lines.append(
            "- Status values outside the README vocabulary are in use: "
            + ", ".join(f"`{s}`" for s in odd_status[:20])
            + ("" if len(odd_status) <= 20 else f", and {len(odd_status) - 20} more")
        )
    lines.append("")
    lines.append("Neither is corrected automatically; ledgers are evidence and are")
    lines.append("never rewritten by tooling.")
    lines.append("")

    out = "\n".join(lines)

    print(f"{len(entries)} ledgers, {len(by_month)} months")
    print(f"{len(missing_status)} missing a Status line")
    print(f"{len(odd_status)} status values outside the documented vocabulary")

    if args.check:
        print("\n--check: nothing written")
        return 0

    INDEX.write_text(out, encoding="utf-8")
    print(f"\nwrote {INDEX.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
